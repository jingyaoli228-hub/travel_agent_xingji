"""Unit tests for the Stage-3 Activity Card fields (schemas/experience.py)
and the Research Orchestrator's card-enrichment / coverage-check methods.
"""

from __future__ import annotations

from travel_agent.agents.research_agent import ResearchOrchestratorAgent
from travel_agent.schemas.common import Source
from travel_agent.schemas.experience import EXPERIENCE_TYPES, TravelExperience
from travel_agent.schemas.research_result import ResearchResult
from travel_agent.schemas.travel_requirement import TravelRequirement


def _experience(name="Radiantly Alive Yoga", type_="wellness", **kwargs) -> TravelExperience:
    defaults = dict(
        name=name, type=type_, location="乌布中心", region="乌布", rating=4.6,
        source=Source(title=name, url="https://maps.example.com", source_type="google"),
    )
    defaults.update(kwargs)
    return TravelExperience(**defaults)


def test_wellness_is_a_valid_experience_type():
    assert "wellness" in EXPERIENCE_TYPES


def test_stable_id_autogenerated_from_name():
    e1 = _experience()
    e2 = _experience()
    assert e1.id and e1.id == e2.id  # deterministic for the same name
    e3 = _experience(name="Something Else")
    assert e3.id != e1.id


def test_activity_card_text_is_not_just_the_bare_name():
    e = _experience()
    e.short_description = "乌布中心的瑜伽疗愈体验。"
    text = e.to_activity_card_text()
    assert e.name in text
    assert len(text) > len(e.name) + 20
    assert "类别" in text


def test_enrich_activity_cards_heuristic_fills_all_card_fields(no_llm):
    req = TravelRequirement(experience_preferences=["wellness"])
    e = _experience(short_description="", detailed_description="")
    agent = ResearchOrchestratorAgent()
    agent.enrich_activity_cards([e], req)
    assert e.short_description
    assert e.detailed_description
    assert e.why_recommended
    assert e.highlights
    assert e.drawbacks
    assert e.subcategories
    assert e.reservation_required is True  # wellness defaults to reservation-recommended


def test_check_coverage_flags_underrepresented_wellness(no_llm):
    req = TravelRequirement(duration_days=5, daily_attraction_count=3, experience_preferences=["wellness"])
    research = ResearchResult(experiences=[_experience(name=f"景点{i}", type_="landmark") for i in range(10)])
    agent = ResearchOrchestratorAgent()
    coverage = agent.check_coverage(req, research)
    assert "wellness" in coverage["underrepresented_categories"]
    assert coverage["needs_more_research"] is True


def test_trigger_targeted_research_adds_missing_category(no_llm, stub_external_calls):
    req = TravelRequirement(destination="巴厘岛", duration_days=5, daily_attraction_count=3, experience_preferences=["wellness"])
    research = ResearchResult(experiences=[_experience(name=f"景点{i}", type_="landmark") for i in range(10)])
    agent = ResearchOrchestratorAgent()
    updated = agent.trigger_targeted_research(req, research)
    assert len(updated.experiences) > len(research.experiences)
